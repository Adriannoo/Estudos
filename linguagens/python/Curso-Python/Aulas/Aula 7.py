print('Operadores Aritiméticos')
n1 = int(input('Digite um valor = '))
n2 = int(input('Digite outro valor = '))
s = n1+n2
m = n1*n2
d = n1/n2
di = n1//n2
p = n1**n2
print('A soma dos valores é = {}'.format(s))
print('A multiplicação dos valores é = {}'.format(m))
print('A divisão dos valores é = {:.3f}'.format(d))
print('A divisão inteira dos valores é = {}'.format(di))
print('A potência dos valores é = {}'.format(p))
